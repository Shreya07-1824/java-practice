package com.tka.operator;

public class AssignOperator30 {
	public static void main(String[] args) {
		
	
	int a=10;
    System.out.println(a);
    a=a+5;
    System.out.println(a);
    a-=3;
    System.out.println(a);
    a/=2;
    System.out.println(a);
    a%=2;
    System.out.println(a);
	} 

}
