package com.tka.operator;

public class IncreDecre30 {
	public static void main(String[] args) {
		int y=10;
		System.out.println(y);
		++y;
		System.out.println(y);
		int a=10;
		a++;
		System.out.println(a);
		int s=10;
		--s;
		System.out.println(s);
		int r=10;
		r--;
		System.out.println(r);
		
	}

}
